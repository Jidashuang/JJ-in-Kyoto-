/**
 * Downloads every remote hero/gallery image referenced in real-places.ts into
 * public/images/places/<slug>/ and regenerates src/data/local-image-manifest.ts.
 *
 *   npm run images:localize            # download missing images
 *   npm run images:localize -- --force # re-download everything
 *
 * Needs outbound network access to the source hosts. Failed downloads are
 * reported and left on their remote URL, so the site keeps working.
 * Check each source's usage rights before committing the downloaded files.
 */
import { mkdir, writeFile, access } from "node:fs/promises";
import path from "node:path";
import { realPlaces } from "../src/data/real-places";

const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "public/images/places");
const MANIFEST = path.join(ROOT, "src/data/local-image-manifest.ts");
const force = process.argv.includes("--force");

const EXT_BY_TYPE: Record<string, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/avif": "avif",
  "image/gif": "gif",
};

const exists = (p: string) => access(p).then(() => true, () => false);

async function download(url: string, base: string): Promise<string | null> {
  // Reuse a previous download unless --force.
  if (!force) {
    for (const ext of Object.values(EXT_BY_TYPE)) {
      if (await exists(`${base}.${ext}`)) return `${base}.${ext}`;
    }
  }
  try {
    const res = await fetch(url, {
      headers: { "user-agent": "Mozilla/5.0 (kyoto-guide image localizer)" },
      signal: AbortSignal.timeout(20_000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const type = (res.headers.get("content-type") ?? "").split(";")[0].trim();
    const ext = EXT_BY_TYPE[type];
    if (!ext) throw new Error(`unsupported content-type "${type}"`);
    await writeFile(`${base}.${ext}`, Buffer.from(await res.arrayBuffer()));
    return `${base}.${ext}`;
  } catch (err) {
    console.warn(`  fail ${url}: ${(err as Error).message}`);
    return null;
  }
}

const toPublicPath = (abs: string) =>
  "/" + path.relative(path.join(ROOT, "public"), abs).split(path.sep).join("/");

async function main() {
  const manifest: Record<string, { hero?: string; gallery?: string[] }> = {};
  let ok = 0;
  let failed = 0;

  for (const place of realPlaces) {
    const urls = [...new Set([place.heroImage, ...(place.gallery ?? [])])].filter(
      (u): u is string => Boolean(u && /^https?:\/\//.test(u)),
    );
    if (urls.length === 0) continue;

    const dir = path.join(OUT_DIR, place.slug);
    await mkdir(dir, { recursive: true });
    console.log(place.slug);

    const local = new Map<string, string>();
    for (const [i, url] of urls.entries()) {
      const file = await download(url, path.join(dir, String(i + 1)));
      if (file) {
        local.set(url, toPublicPath(file));
        ok++;
      } else failed++;
    }

    const entry: { hero?: string; gallery?: string[] } = {};
    if (place.heroImage && local.has(place.heroImage)) entry.hero = local.get(place.heroImage);
    const gallery = (place.gallery ?? []).map((u) => local.get(u)).filter((u): u is string => !!u);
    if (gallery.length) entry.gallery = gallery;
    if (entry.hero || entry.gallery) manifest[place.slug] = entry;
  }

  const body = `// Generated by \`npm run images:localize\` — do not edit by hand.
import type { LocalPlaceImages } from "@/data/image-assets";

export const localImageManifest: Record<string, LocalPlaceImages> = ${JSON.stringify(manifest, null, 2)};
`;
  await writeFile(MANIFEST, body);
  console.log(`\n${ok} downloaded/reused, ${failed} failed, ${Object.keys(manifest).length} places in manifest`);
}

main();
